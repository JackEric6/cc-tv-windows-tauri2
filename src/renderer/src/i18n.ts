function normalizeJsxText(value: string): string {
  const lines = value.split(/\r\n|\n|\r/)
  let lastNonEmpty = 0
  for (let i = 0; i < lines.length; i++) if (/\S/.test(lines[i])) lastNonEmpty = i
  let result = ''
  for (let i = 0; i < lines.length; i++) {
    let line = lines[i].replace(/\t/g, ' ')
    if (i !== 0) line = line.replace(/^\s+/, '')
    if (i !== lastNonEmpty) line = line.replace(/\s+$/, '')
    if (line) result += line + (i !== lastNonEmpty ? ' ' : '')
  }
  return result
}

export function setUiLanguage(language: UiLanguage): void {
  currentLanguage = language
  document.documentElement.lang = language === 'en-US' ? 'en' : 'zh-CN'
}

export function translate(value: string): string {
  const text = normalizeJsxText(value)
  if (currentLanguage !== 'en-US') return text
  const leading = text.match(/^\s*/)?.[0] ?? ''
  const trailing = text.match(/\s*$/)?.[0] ?? ''
  const key = text.trim()
  return `${leading}${english[key] ?? key}${trailing}`
}
